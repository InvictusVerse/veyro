package com.veyro.core.link.media

import com.veyro.core.link.media.MediaVectors.hex
import com.veyro.core.protocol.AeadStreamException
import com.veyro.core.protocol.media.AccessUnitFragmenter
import com.veyro.core.protocol.media.Vms1
import com.veyro.core.protocol.media.Vms1Channel
import com.veyro.core.protocol.media.Vms1Frame
import kotlinx.serialization.json.boolean
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Assert.fail
import org.junit.Test
import java.io.ByteArrayInputStream
import java.io.ByteArrayOutputStream

/**
 * The VMS1 media socket against `protocol/testvectors/media/vms1.json` (generated by
 * `tools/GenVms1.java` with JDK primitives). The Windows suite drives the same file, so both
 * clients produce and accept the same bytes.
 */
class Vms1VectorTest {

    private val v = MediaVectors.load("media/vms1.json")
    private val sid = hex(v.str("sid"))
    private val saltPhone = hex(v.str("saltPhone"))
    private val saltPc = hex(v.str("saltPc"))
    private val okm get() = hex(v.str("okm"))
    private val records = v.getValue("records").jsonArray.map { it.jsonObject }

    private fun kotlinx.serialization.json.JsonObject.str(key: String) = getValue(key).jsonPrimitive.content
    private fun record(name: String) = records.single { it.str("name") == name }
    private fun recordBytes(dir: String) = records.filter { it.str("dir") == dir }.map { hex(it.str("record")) }
        .fold(ByteArray(0)) { acc, b -> acc + b }

    @Test
    fun `prefaces, context and label match`() {
        assertEquals(v.str("phonePreface"), hex(Vms1.encodePreface(Vms1.SOURCE_SCREEN, sid, saltPhone)))
        assertEquals(v.str("pcPreface"), hex(Vms1.encodePreface(Vms1.SOURCE_SCREEN, sid, saltPc)))
        assertEquals(v.str("exportContext"), hex(Vms1.exportContext(Vms1.SOURCE_SCREEN, sid, saltPhone, saltPc)))
        assertEquals(v.str("exportLabel"), Vms1.exportLabel(Vms1.SOURCE_SCREEN))
        val parsed = Vms1.parsePreface(hex(v.str("phonePreface")))
        assertEquals(Vms1.SOURCE_SCREEN, parsed.source)
        assertArrayEquals(sid, parsed.sid)
        assertArrayEquals(saltPhone, parsed.salt)
    }

    @Test
    fun `bad prefaces are refused`() {
        for (bad in v.getValue("badPrefaces").jsonArray.map { it.jsonObject }) {
            try {
                Vms1.parsePreface(hex(bad.str("bytes")))
                fail("accepted: ${bad.str("why")}")
            } catch (_: AeadStreamException) {
            }
        }
    }

    @Test
    fun `plaintexts match`() {
        assertEquals(record("auth").str("plaintext"), hex(Vms1.encodeAuth(v.str("phoneId"), v.str("pcId"), Vms1.SOURCE_SCREEN, sid)))
        assertEquals(record("videoConfig").str("plaintext"), hex(Vms1.encodeVideoConfig(videoConfig())))
        assertEquals(record("audioConfig").str("plaintext"), hex(Vms1.encodeAudioConfig(Vms1.AudioConfig(channels = 2, rate = 48_000))))
        assertEquals(record("close").str("plaintext"), hex(Vms1.encodeClose(0, "user")))
    }

    @Test
    fun `the phone's writer produces the upward records byte for byte`() {
        val out = ByteArrayOutputStream()
        val channel = Vms1Channel.fromOkm(ByteArrayInputStream(ByteArray(0)), out, okm, phone = true)
        channel.writer.writeAuth(v.str("phoneId"), v.str("pcId"), Vms1.SOURCE_SCREEN, sid)
        channel.writer.writeVideoConfig(videoConfig())
        channel.writer.writeAudioConfig(Vms1.AudioConfig(channels = 2, rate = 48_000))
        val au = ByteArray(20) { (0xA0 + it).toByte() }
        channel.writer.writeAccessUnit(1_000_000L, au, 0, au.size, key = true, discontinuity = false)
        val samples = ByteArray(8) { (1 + it).toByte() }
        channel.writer.writeAudio(1_005_000L, samples, 0, samples.size)
        channel.writer.writeClose(0, "user")
        assertEquals(hex(recordBytes("up")), hex(out.toByteArray()))
        channel.close()
    }

    @Test
    fun `the PC's writer produces AUTH_ACK and the phone reads it`() {
        val out = ByteArrayOutputStream()
        Vms1Channel.fromOkm(ByteArrayInputStream(ByteArray(0)), out, okm, phone = false).writer.writeAuthAck()
        assertEquals(hex(recordBytes("down")), hex(out.toByteArray()))
        val phone = Vms1Channel.fromOkm(ByteArrayInputStream(out.toByteArray()), ByteArrayOutputStream(), okm, phone = true)
        val ack = phone.reader.read() as Vms1Frame.AuthAck
        assertEquals(0, ack.status)
        assertNull(phone.reader.read())
    }

    @Test
    fun `a PC-side reader decodes every upward record`() {
        val pc = Vms1Channel.fromOkm(ByteArrayInputStream(recordBytes("up")), ByteArrayOutputStream(), okm, phone = false)
        val auth = (pc.reader.read() as Vms1Frame.Auth).auth
        assertEquals(v.str("phoneId"), auth.phoneId)
        assertEquals(v.str("pcId"), auth.pcId)
        assertArrayEquals(sid, auth.sid)
        assertEquals(videoConfig(), (pc.reader.read() as Vms1Frame.VideoConfig).config)
        assertEquals(Vms1.AudioConfig(channels = 2, rate = 48_000), (pc.reader.read() as Vms1Frame.AudioConfig).config)
        val video = pc.reader.read() as Vms1Frame.Video
        assertEquals(Vms1.FLAG_KEY or Vms1.FLAG_START or Vms1.FLAG_END, video.flags)
        assertEquals(1_000_000L, video.ptsUs)
        assertEquals(20, video.auLength)
        assertArrayEquals(ByteArray(20) { (0xA0 + it).toByte() }, video.data)
        val audio = pc.reader.read() as Vms1Frame.Audio
        assertEquals(1_005_000L, audio.ptsUs)
        assertEquals(8, audio.samples.size)
        assertEquals("user", (pc.reader.read() as Vms1Frame.Close).close.reason)
        assertNull(pc.reader.read())
    }

    @Test
    fun `a changed byte, a dropped record or a replayed one fails to open`() {
        val up = recordBytes("up")
        val tampered = up.copyOf().also { it[it.size - 1] = (it[it.size - 1].toInt() xor 1).toByte() }
        assertReadFails(tampered, skip = 5)

        // AUTH, then VIDEO_CONFIG missing: AUDIO_CONFIG is opened with counter 1 and fails.
        val auth = hex(record("auth").str("record"))
        val rest = hex(record("audioConfig").str("record"))
        assertReadFails(auth + rest, skip = 1)

        // AUTH twice: the second copy is opened with counter 1.
        assertReadFails(auth + auth, skip = 1)
    }

    @Test
    fun `the first record must be the handshake one`() {
        assertReadFails(hex(record("videoConfig").str("record")), skip = 0)
    }

    @Test
    fun `header rules`() {
        for (h in v.getValue("badHeaders").jsonArray.map { it.jsonObject }) {
            try {
                Vms1.checkHeader(h.int("kind"), h.int("flags"), h.int("length"), h.getValue("fromPhone").jsonPrimitive.boolean)
                fail("accepted: ${h.str("why")}")
            } catch (_: AeadStreamException) {
            }
        }
        for (h in v.getValue("goodHeaders").jsonArray.map { it.jsonObject }) {
            Vms1.checkHeader(h.int("kind"), h.int("flags"), h.int("length"), h.getValue("fromPhone").jsonPrimitive.boolean)
        }
    }

    @Test
    fun `the writer refuses media before its config`() {
        val writer = Vms1Channel.fromOkm(ByteArrayInputStream(ByteArray(0)), ByteArrayOutputStream(), okm, phone = true).writer
        assertFalse(runCatching { writer.writeAccessUnit(0, ByteArray(4), 0, 4, key = true, discontinuity = false) }.isSuccess)
        assertFalse(runCatching { writer.writeAudio(0, ByteArray(4), 0, 4) }.isSuccess)
        writer.writeAudioConfig(Vms1.AudioConfig(channels = 2, rate = 48_000))
        assertFalse("half a stereo frame", runCatching { writer.writeAudio(0, ByteArray(2), 0, 2) }.isSuccess)
        assertTrue(runCatching { writer.writeAudio(0, ByteArray(4), 0, 4) }.isSuccess)
    }

    @Test
    fun `a large keyframe goes out in fragments that a reader puts back`() {
        val out = ByteArrayOutputStream()
        val phone = Vms1Channel.fromOkm(ByteArrayInputStream(ByteArray(0)), out, okm, phone = true)
        phone.writer.writeAuth(v.str("phoneId"), v.str("pcId"), Vms1.SOURCE_SCREEN, sid)
        phone.writer.writeVideoConfig(videoConfig())
        val au = ByteArray(150_000) { (it * 31).toByte() }
        phone.writer.writeAccessUnit(5L, au, 0, au.size, key = true, discontinuity = true)
        val pc = Vms1Channel.fromOkm(ByteArrayInputStream(out.toByteArray()), ByteArrayOutputStream(), okm, phone = false)
        pc.reader.read()
        pc.reader.read()
        val plan = AccessUnitFragmenter.plan(au.size, key = true, discontinuity = true)
        val joined = ByteArrayOutputStream()
        for (expected in plan) {
            val fragment = pc.reader.read() as Vms1Frame.Video
            assertEquals(expected.flags, fragment.flags)
            assertEquals(expected.length, fragment.data.size)
            joined.write(fragment.data)
        }
        assertArrayEquals(au, joined.toByteArray())
        assertNull(pc.reader.read())
    }

    private fun assertReadFails(bytes: ByteArray, skip: Int) {
        val pc = Vms1Channel.fromOkm(ByteArrayInputStream(bytes), ByteArrayOutputStream(), okm, phone = false)
        repeat(skip) { pc.reader.read() }
        try {
            pc.reader.read()
            fail("a bad record was accepted")
        } catch (_: AeadStreamException) {
        }
        // The reader stays failed.
        try {
            pc.reader.read()
            fail("a failed reader read again")
        } catch (_: AeadStreamException) {
        }
    }

    private fun kotlinx.serialization.json.JsonObject.int(key: String) = getValue(key).jsonPrimitive.int

    private fun videoConfig() = Vms1.VideoConfig(
        codec = Vms1.VIDEO_CODEC_H264, width = 1072, height = 2448,
        visX = 0, visY = 0, visW = 1072, visH = 2448, rotation = 0, mirror = false, generation = 1,
    )
}
